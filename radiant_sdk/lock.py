"""``radiant-sdk lock``: requirements.in -> a hash-locked requirements.lock.

The validator installs a solution's lock with ``pip install --no-deps
--require-hashes`` on top of the SDK's base image, so the lock must:

* pin every package the solution needs beyond the base image, with hashes,
  for the sandbox platform (linux x86_64, Python 3.12), and
* leave out what the base image already has (torch, torchvision, numpy,
  pillow, safetensors and their dependencies), so nothing is replaced.

This wraps ``uv pip compile`` with the base image as constraints and the
base packages excluded. It needs uv (https://docs.astral.sh/uv/).
"""

from __future__ import annotations

import re
import shutil
import subprocess
import tempfile
from pathlib import Path

from . import reasons as R
from .checks import check_lock

BASE = Path(__file__).resolve().parent / "base_image" / "requirements.txt"
PLATFORM = ("--python-version", "3.12", "--python-platform", "x86_64-manylinux_2_28")


def base_packages() -> list[str]:
    names = re.findall(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==", BASE.read_text(), flags=re.M)
    return sorted({n.lower().replace("_", "-") for n in names})


def lock(requirements_in: Path, output: Path) -> list[str]:
    uv = shutil.which("uv")
    if uv is None:
        raise ValueError("radiant-sdk lock needs uv: https://docs.astral.sh/uv/getting-started/installation/")
    excluded = [arg for name in base_packages() for arg in ("--no-emit-package", name)]
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "requirements.lock"
        cmd = [uv, "pip", "compile", str(requirements_in), "-c", str(BASE), *PLATFORM,
               "--generate-hashes", "--no-header", "-q", "-o", str(out), *excluded]
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode != 0:
            raise ValueError(f"uv pip compile failed:\n{result.stderr.strip()[-2000:]}")
        text = out.read_text()
    header = ("# Generated by `radiant-sdk lock` for linux x86_64 / Python 3.12.\n"
              "# Base image packages are excluded; the validator installs this with --no-deps --require-hashes.\n")
    pins = check_lock(text)  # same rules the validator applies
    output.write_text(header + text)
    return pins


def main(requirements_in: str, output: str) -> int:
    try:
        pins = lock(Path(requirements_in), Path(output))
    except R.SolutionRejected as exc:
        raise ValueError(f"the generated lock fails {exc.code}: {exc.detail}") from None
    print(f"wrote {output}: {len(pins)} packages beyond the base image")
    return 0
